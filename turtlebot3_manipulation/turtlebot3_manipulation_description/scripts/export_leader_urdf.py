#!/usr/bin/env python3
"""Export the portable, multi-material RViz-compatible leader display URDF.

Humble RViz 11.2.29 passes an empty material name for every visual in a link,
so all those visuals inherit its first material. Group additional materials
under identity fixed children; never change an existing joint or geometry.
"""
import argparse
from pathlib import Path
import subprocess
import xml.etree.ElementTree as ET


def split_visual_materials(root):
    """Idempotent display-only conversion; original links/collisions stay put."""
    names={n.get('name') for n in root if n.tag in ('link','joint')}
    for link in list(root.findall('link')):
        groups={}
        for visual in link.findall('visual'):
            material=visual.find('material')
            key=ET.tostring(material,encoding='unicode').strip() if material is not None else ''
            groups.setdefault(key,[]).append(visual)
        for index,visuals in enumerate(list(groups.values())[1:],1):
            child_name=f"{link.get('name')}__visual_{index}"
            joint_name=child_name+'_fixed'
            if child_name in names or joint_name in names:
                raise ValueError(f'Visual compatibility name collision: {child_name}')
            names.update((child_name,joint_name))
            child=ET.SubElement(root,'link',name=child_name)
            for visual in visuals:
                link.remove(visual)
                child.append(visual)
            joint=ET.SubElement(root,'joint',name=joint_name,type='fixed')
            ET.SubElement(joint,'parent',link=link.get('name'))
            ET.SubElement(joint,'child',link=child_name)
            ET.SubElement(joint,'origin',xyz='0 0 0',rpy='0 0 0')
    return root


def main():
    package = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,default=package/'urdf/leader_turtlebot3.urdf')
    parser.add_argument('--stdout',action='store_true',help='Emit XML without writing a file (launch)')
    parser.add_argument('--xacro-arg',action='append',default=[],help='Forward one name:=value to xacro')
    args = parser.parse_args()
    text = subprocess.check_output(['xacro',str(package/'xacro/leader_turtlebot3.urdf.xacro'),*args.xacro_arg],text=True)
    root = split_visual_materials(ET.fromstring(text))
    for mesh in root.findall('.//mesh'):
        uri = mesh.get('filename')
        if uri.startswith('file://') and '/meshes/' in uri:
            mesh.set('filename','package://turtlebot3_manipulation_description/meshes/'+uri.split('/meshes/',1)[1])
    ET.indent(root,space='  ')
    xml='<?xml version="1.0"?>\n<!-- Generated by scripts/export_leader_urdf.py; edit xacro sources. -->\n'+ET.tostring(root,encoding='unicode')+'\n'
    if args.stdout:
        print(xml,end='')
    else:
        args.output.parent.mkdir(parents=True,exist_ok=True)
        args.output.write_text(xml)
        print(args.output)


if __name__ == '__main__':
    main()
